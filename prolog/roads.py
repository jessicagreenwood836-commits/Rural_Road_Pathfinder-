"""Rural road network admin (Req 1 + 2).

Prolog (rules.pl over the facts in roads.pl) reads the data and does all the
reasoning: bidirectional roads, the +5 minute rule, hazard inference, closures
and explanations. This file collects admin input, validates it, writes the
facts back to roads.pl, and shows what Prolog derived.
"""
import math
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROADS_FILE = os.path.join(HERE, "roads.pl")
RULES_FILE = os.path.join(HERE, "rules.pl")

ROAD_TYPES = ("paved", "unpaved")
CONDITIONS = ("broken_cisterns", "deep_potholes", "severely_damaged", "falling_rocks")
STATUSES = ("open", "closed")
DIRECTIONS = ("two_way", "one_way")
SEASONAL = ("none", "rainy")
SEASONS = ("dry", "rainy")

# Column order of each dump_roads line (stored fields, then derived by Prolog).
FIELDS = ("source", "dest", "km", "mins", "type", "conditions", "pothole_inches",
          "status", "direction", "seasonal",
          "effective_mins", "effective_status", "reasons")

HEADER = """\
:- encoding(utf8).
% roads.pl - Rural road network facts. Generated by roads.py; use its admin menu.
% road(Source, Dest, Km, BaseMins, Type, Conditions, PotholeInches,
%      Status, Direction, Seasonal).
%   Type          : paved | unpaved
%   Conditions    : list of broken_cisterns, deep_potholes, severely_damaged,
%                   falling_rocks ([] = none)
%   PotholeInches : measured depth, 0 = not measured (> 3 => deep_potholes)
%   Status        : open | closed (closed = blocked by admin)
%   Direction     : two_way | one_way (one_way = only Source -> Dest)
%   Seasonal      : none | rainy (rainy = blocked in the rainy season)
%   BaseMins excludes the +5 delay; rules.pl derives it with travel_time/3.
%
% Sample rows from the assignment brief, in the original format:
%   A -> B  5 km 10 min paved   none            open
%   B -> C  3 km 15 min unpaved broken cisterns open
%   C -> D  7 km 12 min paved   deep potholes   closed
:- dynamic road/10.
:- dynamic current_season/1.
"""


# ---------------------------------------------------------------- Prolog I/O

def query_prolog(goal):
    """Run a goal against rules.pl and return its output lines split on tabs.

    A Prolog warning or error (e.g. a syntax error in roads.pl) stops the
    program, because Prolog would otherwise silently skip the bad facts.
    """
    if shutil.which("swipl") is None:
        sys.exit("SWI-Prolog (swipl) is not installed. Install it first, e.g.\n"
                 "  sudo apt install swi-prolog   or   https://www.swi-prolog.org/download")
    # Force UTF-8 output so non-ASCII names survive whatever the system locale is.
    result = subprocess.run(["swipl", "-q", "-g", f"set_stream(user_output,encoding(utf8)),{goal}",
                             "-t", "halt", RULES_FILE],
                            capture_output=True, text=True, encoding="utf-8", cwd=HERE)
    if result.returncode != 0 or "Warning:" in result.stderr or "ERROR" in result.stderr:
        sys.exit(f"Prolog could not read the road data:\n{result.stderr.strip()}")
    return [line.split("\t") for line in result.stdout.splitlines() if line]


def load_roads():
    """Read the season and every road through Prolog. Returns (roads, season)."""
    lines = query_prolog("dump_roads")
    season = lines[0][0]
    roads = []
    for line in lines[1:]:
        r = dict(zip(FIELDS, line + [""] * (len(FIELDS) - len(line))))
        r["km"] = float(r["km"])
        r["mins"] = int(r["mins"])
        r["pothole_inches"] = float(r["pothole_inches"])
        r["effective_mins"] = int(r["effective_mins"])
        r["conditions"] = r["conditions"].split(",") if r["conditions"] else []
        roads.append(r)
    return roads, season


def pl_atom(name):
    """Quote a place name as a Prolog atom: 'Mary''s Town'."""
    return "'" + name.replace("\\", "\\\\").replace("'", "''") + "'"


def pl_number(x):
    """Write a number without a trailing .0 when it is whole."""
    return str(int(x)) if float(x).is_integer() else str(x)


def save_roads(roads, season):
    """Rewrite roads.pl with the season and every road fact.

    Written to a temp file first, so a crash mid-write cannot corrupt the data."""
    tmp = ROADS_FILE + ".tmp"
    try:
        _write_roads(tmp, roads, season)
        os.replace(tmp, ROADS_FILE)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)


def _write_roads(path, roads, season):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(HEADER)
        fh.write(f"\ncurrent_season({season}).\n\n")
        for r in roads:
            fh.write(
                f"road({pl_atom(r['source'])}, {pl_atom(r['dest'])}, {pl_number(r['km'])}, "
                f"{r['mins']}, {r['type']}, [{', '.join(r['conditions'])}], "
                f"{pl_number(r['pothole_inches'])}, {r['status']}, {r['direction']}, "
                f"{r['seasonal']}).\n")


# ---------------------------------------------------------------- validation

def clean_name(name):
    """Tidy a place name: trim and collapse spaces, keep the admin's capitals."""
    return " ".join(name.split())


def valid_name(name):
    """Letters, digits, spaces and . ' - only (no backslashes, tabs or quotes
    that would break the Prolog file or the tab-separated dump)."""
    return bool(name) and all(ch.isalnum() or ch in " .'-" for ch in name)


def validate_road(r):
    """Return a list of problems with a road (empty list = valid)."""
    errors = []
    if not valid_name(r["source"]) or not valid_name(r["dest"]):
        errors.append("place names may only use letters, digits, spaces and . ' -")
    if r["source"].casefold() == r["dest"].casefold():
        errors.append("source and dest must differ")
    if not math.isfinite(r["km"]) or r["km"] <= 0:
        errors.append("distance must be a positive number of km")
    if r["mins"] <= 0:
        errors.append("travel time must be greater than 0 minutes")
    if not math.isfinite(r["pothole_inches"]) or r["pothole_inches"] < 0:
        errors.append("pothole depth must be 0 or more inches")
    for key, allowed in (("type", ROAD_TYPES), ("status", STATUSES),
                         ("direction", DIRECTIONS), ("seasonal", SEASONAL)):
        if r[key] not in allowed:
            errors.append(f"{key} must be one of {', '.join(allowed)}")
    for c in r["conditions"]:
        if c not in CONDITIONS:
            errors.append(f"unknown condition: {c}")
    return errors


def find_road(roads, a, b):
    """Find the road between two places, stored in either direction.
    Case-insensitive, so 'papine' and 'Papine' are the same place."""
    wanted = {a.casefold(), b.casefold()}
    for r in roads:
        if {r["source"].casefold(), r["dest"].casefold()} == wanted:
            return r
    return None


def canon_place(roads, name):
    """Reuse the spelling already in the network. Prolog atoms are case-sensitive,
    so a new road to 'papine' would otherwise be a second, unconnected node."""
    for r in roads:
        for place in (r["source"], r["dest"]):
            if place.casefold() == name.casefold():
                return place
    return name


# ---------------------------------------------------------------- input helpers

def ask_text(prompt, default=None):
    """Ask for text; Enter keeps the default if there is one."""
    while True:
        shown = f" [{default}]" if default is not None else ""
        value = input(f"{prompt}{shown}: ").strip()
        if value:
            return value
        if default is not None:
            return default
        print("  Value required.")


def ask_number(prompt, kind=float, default=None):
    """Ask for a number; range checks are done by validate_road."""
    while True:
        raw = ask_text(prompt, None if default is None else pl_number(default))
        try:
            return kind(raw)
        except ValueError:
            print("  Enter a number.")


def ask_choice(prompt, options, default=None, multi=False):
    """Pick one option by number, or several ('1,3', '0' = none) when multi."""
    print(f"{prompt}:")
    for i, opt in enumerate(options, 1):
        print(f"  {i}. {opt}")
    if multi:
        print("  (comma-separated numbers, 0 = none)")
    if default is None:
        shown = None
    elif multi:
        shown = ",".join(str(options.index(d) + 1) for d in default) or "0"
    else:
        shown = str(options.index(default) + 1)
    while True:
        picks = ask_text("Choose", shown).replace(" ", "").split(",")
        if multi and picks == ["0"]:
            return []
        valid = all(p.isdecimal() and 1 <= int(p) <= len(options) for p in picks)
        if valid and (multi or len(picks) == 1):
            chosen = []
            for p in picks:
                if options[int(p) - 1] not in chosen:
                    chosen.append(options[int(p) - 1])
            return chosen if multi else chosen[0]
        print("  Invalid choice.")


def ask_fields(d):
    """Ask for every editable road field; d holds the defaults (may be empty)."""
    return {
        "km": ask_number("Distance (km)", default=d.get("km")),
        "mins": ask_number("Base travel time (minutes, without delays)", int, d.get("mins")),
        "type": ask_choice("Road type", ROAD_TYPES, d.get("type")),
        "conditions": ask_choice("Conditions", CONDITIONS, d.get("conditions"), multi=True),
        "pothole_inches": ask_number("Deepest pothole in inches (0 = none)",
                                     default=d.get("pothole_inches", 0)),
        "status": ask_choice("Status", STATUSES, d.get("status")),
        "direction": ask_choice("Direction", DIRECTIONS, d.get("direction")),
        "seasonal": ask_choice("Seasonally blocked", SEASONAL, d.get("seasonal")),
    }


# ---------------------------------------------------------------- display

def describe(r):
    """One-line summary of a road's derived state, e.g. '17 min, closed - ...'."""
    text = f"{r['effective_mins']} min, {r['effective_status']}"
    if r["reasons"]:
        text += " - " + r["reasons"]
    return text


def show_roads(roads, season):
    """Table of stored facts plus what Prolog derived from them."""
    print(f"\nSeason: {season}.  Base = stored minutes; "
          "Eff = minutes after the Prolog +5 rule; Now = status after closure rules.")
    w = max([16] + [len(p) for r in roads for p in (r["source"], r["dest"])]) + 2
    print(f"{'Source':<{w}}{'Dest':<{w}}{'Km':>4}{'Base':>5}{'Eff':>5}  "
          f"{'Type':<8}{'Dir':<8}{'Now':<7}Conditions")
    for r in roads:
        conds = ",".join(r["conditions"]) or "none"
        if r["pothole_inches"]:
            conds += f" ({pl_number(r['pothole_inches'])} in)"
        if r["seasonal"] == "rainy":
            conds += " [seasonal]"
        print(f"{r['source']:<{w}}{r['dest']:<{w}}{pl_number(r['km']):>4}{r['mins']:>5}"
              f"{r['effective_mins']:>5}  {r['type']:<8}{r['direction']:<8}"
              f"{r['effective_status']:<7}{conds}")


def show_connections(roads, season):
    """Every drivable direction, as Prolog's connected/4 reports it."""
    print("\nOpen, drivable connections (connected/4, bidirectional rule applied):")
    for source, dest, km, mins in query_prolog("dump_edges"):
        print(f"  {source} -> {dest}: {pl_number(float(km))} km, {mins} min")


def explain_road(roads, season):
    """Print Prolog's why/3 explanation for one road."""
    r = find_road(roads, clean_name(ask_text("From")), clean_name(ask_text("To")))
    if r:
        print(f"{r['source']} - {r['dest']}: base {r['mins']} min -> {describe(r)}")
    else:
        print("No such road.")


# ---------------------------------------------------------------- admin actions

def edit_road(roads, season, road=None):
    """Add a new road (road=None) or update an existing one, then save."""
    if road is None:
        source = canon_place(roads, clean_name(ask_text("Source village/town")))
        dest = canon_place(roads, clean_name(ask_text("Destination village/town")))
        if find_road(roads, source, dest):
            print("A road between those places already exists. Use update instead.")
            return
        before = None
        road = {"source": source, "dest": dest}
        roads.append(road)
    else:
        before = dict(road)
        print(f"Updating {road['source']} -> {road['dest']}. Press Enter to keep a value.")

    road.update(ask_fields(road))
    if before and road["direction"] == "one_way":
        swap = ask_text(f"Swap to {road['dest']} -> {road['source']}? (y/n)", "n")
        if swap.lower().startswith("y"):
            road["source"], road["dest"] = road["dest"], road["source"]

    errors = validate_road(road)
    if errors:
        print("Not saved: " + "; ".join(errors))
        if before:
            road.clear()
            road.update(before)
        else:
            roads.remove(road)
        return

    save_roads(roads, season)
    new_roads, _ = load_roads()   # re-read so Prolog applies the rules
    after = find_road(new_roads, road["source"], road["dest"])
    print("Saved to roads.pl.")
    if before:
        print(f"  before: {describe(before)}")
    print(f"  now:    {describe(after)}")


def add_road(roads, season):
    """Menu action: add a road."""
    edit_road(roads, season)


def update_road(roads, season):
    """Menu action: pick a road and update it."""
    road = find_road(roads, clean_name(ask_text("From")), clean_name(ask_text("To")))
    if road:
        edit_road(roads, season, road)
    else:
        print("No such road.")


def set_season(roads, season):
    """Change the current season; seasonal roads close in the rainy season."""
    new = ask_choice("Current season", SEASONS, season)
    save_roads(roads, new)
    new_roads, _ = load_roads()
    closed = [f"{r['source']} - {r['dest']}" for r in new_roads
              if "closed in rainy season" in r["reasons"]]
    print(f"Season set to {new}. Seasonal roads closed: {', '.join(closed) or 'none'}.")


MENU = {
    "1": ("List roads", show_roads),
    "2": ("List open connections", show_connections),
    "3": ("Add road", add_road),
    "4": ("Update road", update_road),
    "5": ("Explain a road (why)", explain_road),
    "6": ("Set season", set_season),
}


def main():
    while True:
        roads, season = load_roads()  # reload through Prolog every loop
        print("\n=== Rural Road Network Admin ===")
        for key, (label, _) in MENU.items():
            print(f"{key}. {label}")
        print("7. Quit")
        choice = input("Choice: ").strip()
        if choice == "7":
            break
        if choice in MENU:
            MENU[choice][1](roads, season)
        else:
            print("Pick 1-7.")


if __name__ == "__main__":
    try:
        main()
    except (EOFError, KeyboardInterrupt):
        print()
    except OSError as e:
        sys.exit(f"File error: {e}")


